def render_publication_pdf_master(config: SitePublicationDialogConfig) -> str:
    lines: list[str] = [
        "% Provisional publication PDF master generated by Ekdosis-TEI Studio.",
        "% This file is an internal build artifact for the future complete publication PDF.",
        render_purh_publication_preamble(config),
        "",
        r"\begin{document}",
        rf"\setpurhrunningauthor{{{_latex_text(config.author_name)}}}",
        r"\pagenumbering{arabic}",
        r"\pagestyle{fancy}",
        "% Corpus-level title page intentionally omitted in per-play PDF.",
        "% The visible title page is generated below by \\playtitlepage.",
    ]

    # Disabled intentionally: per-play PDFs must not start with the
    # corpus-level title page. Keeping these lines here makes it easy to
    # restore them later for a complete-corpus PDF.
    #
    # lines.extend(
    #     [
    #         rf"\title{{{_latex_text(config.corpus_title or 'Edition')}}}",
    #         rf"\author{{{_latex_text(config.author_name)}}}",
    #         r"\date{}",
    #         r"\frontmatter",
    #         r"\maketitle",
    #         r"\mainmatter",
    #     ]
    # )

   #  lines.extend(["", r"\mainmatter"])

    if config.general_intro_tei is not None:
        lines.extend(
            [
                "",
                "% GENERAL INTRO intentionally omitted from per-play PDF.",
                f"% GENERAL INTRO source: {_path_comment(config.general_intro_tei)}",
            ]
        )

        # Disabled intentionally: the general corpus introduction does not belong
        # in per-play publication PDFs. Keep this block here so it can be
        # restored easily if a future complete-corpus PDF is added.
        #
        # lines.extend(
        #     [
        #         "",
        #         rf"\setpurhrunningauthor{{{_latex_text(config.author_name)}}}",
        #         r"\setpurhrunningtitle{Introduction générale}",
        #         r"\publicationsection{Introduction générale}{Introduction générale}",
        #         f"% GENERAL INTRO: {_path_comment(config.general_intro_tei)}",
        #         _peritext_fragment(config.general_intro_tei),
        #     ]
        # )

    for play in config.plays:
        play_title = _play_title_from_tei(play.dramatic_xml_path)
        editor_credit = (
            f"Texte édité par {config.scientific_editor.strip()}."
            if config.scientific_editor.strip()
            else ""
        )
        dramatis_comment = _dramatis_comment(play.dramatis_xml_path, play.dramatic_xml_path)
        dramatis_fragment = _dramatis_fragment(play.dramatis_xml_path, play.dramatic_xml_path)
        lines.extend(
            [
                "",
                rf"\setpurhrunningauthor{{{_latex_text(config.author_name)}}}",
                rf"\setpurhrunningtitle{{{_latex_text(play_title)}}}",
                rf"\playtitlepage{{{_latex_text(play_title)}}}{{{_latex_text(config.author_name)}}}{{{_latex_text(editor_credit)}}}{{}}",
                f"% PLAY: {_latex_text(play_title)}",
            ]
        )

        if play.notice_xml_path is not None:
            lines.extend(
                [
                    "",
                    rf"\publicationsection{{Notice}}{{{_latex_text(play_title)}}}",
                    f"% NOTICE: {_path_comment(play.notice_xml_path)}",
                    _peritext_fragment(play.notice_xml_path),
                ]
            )

        if play.preface_xml_path is not None:
            lines.extend(
                [
                    "",
                    rf"\publicationsection{{Preface}}{{{_latex_text(play_title)}}}",
                    f"% PREFACE: {_path_comment(play.preface_xml_path)}",
                    _peritext_fragment(play.preface_xml_path),
                ]
            )

        if _has_dramatis_content(dramatis_fragment):
            lines.extend(
                [
                    "",
                    rf"\dramatissection{{{_latex_text(play_title)}}}",
                    dramatis_comment,
                    dramatis_fragment,
                ]
            )
        else:
            lines.extend(["", dramatis_comment, dramatis_fragment])

        lines.extend(
            [
                "",
                rf"\dramatictextsection{{{_latex_text(play_title)}}}",
                f"% DRAMATIC TEXT: {_path_comment(play.dramatic_xml_path)}",
                _dramatic_fragment(
                    play.dramatic_xml_path,
                    hide_minor_variants=config.hide_minor_variants_in_pdf,
                ),
            ]
        )

    lines.extend(["", r"\end{document}", ""])
    return "\n".join(lines)


