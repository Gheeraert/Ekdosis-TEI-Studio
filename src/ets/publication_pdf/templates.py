def _render_publication_reledmac_overrides() -> str:
    return "\n".join(
        [
            r"% Publication PDF overrides for dramatic typography.",
            r"\renewenvironment{speech}{\par\begingroup}{\par\endgroup}",
            r"\renewcommand{\stage}[1]{%",
            r"  \par\addvspace{0.9\baselineskip}%",
            r"  {\centering\normalfont\fontsize{11}{12.6}\selectfont\scshape #1\par}%",
            r"  \addvspace{0.45\baselineskip}%",
            r"}",
            r"\renewcommand{\speaker}[1]{%",
            r"  \par\addvspace{0.6\baselineskip}%",
            r"  {\centering\normalfont\fontsize{10}{11.5}\selectfont\scshape #1\par}%",
            r"  \nobreak%",
            r"}",
            r"\renewcommand{\didas}[1]{%",
            r"  \par\addvspace{0.4\baselineskip}%",
            r"  {\centering\normalfont\small\itshape #1\par}%",
            r"  \addvspace{0.2\baselineskip}%",
            r"}",
        ]
    )

def _latex_text(value: str) -> str:
    return escape_latex_text(value.strip())


def _play_title_from_tei(path: Path) -> str:
    root = etree.parse(str(path)).getroot()
    title = root.xpath("string((.//*[local-name()='titleStmt']/*[local-name()='title'][normalize-space()][1])[1])")
    title_text = " ".join(str(title).split())
    return title_text or "Pièce sans titre"


def _path_comment(path: Path) -> str:
    return str(path.resolve())


def _peritext_fragment(path: Path) -> str:
    return tei_peritext_to_latex(path).rstrip()


def _dramatis_comment(dramatis_xml_path: Path | None, dramatic_xml_path: Path) -> str:
    if dramatis_xml_path is not None:
        return f"% DRAMATIS PERSONAE: {_path_comment(dramatis_xml_path)}"
    return f"% DRAMATIS PERSONAE: front of {_path_comment(dramatic_xml_path)}"


def _dramatis_fragment(dramatis_xml_path: Path | None, dramatic_xml_path: Path) -> str:
    source_path = dramatis_xml_path if dramatis_xml_path is not None else dramatic_xml_path
    return tei_castlist_to_latex(source_path).rstrip()


def _has_dramatis_content(fragment: str) -> bool:
    return bool(fragment.strip()) and "% DRAMATIS PERSONAE: no castList found." not in fragment


def _dramatic_fragment(dramatic_xml_path: Path, *, hide_minor_variants: bool = False) -> str:
    apparatus_policy = "hide_minor" if hide_minor_variants else "full"
    fragment = tei_to_reledmac(
        dramatic_xml_path,
        standalone=False,
        apparatus_policy=apparatus_policy,
        apparatus_numbering_policy="editorial",
    ).rstrip()
    if not fragment:
        return "\n".join(
            [
                r"\begin{PURHDramaticText}",
                r"\beginnumbering",
                r"\endnumbering",
                r"\end{PURHDramaticText}",
            ]
        )
    return "\n".join(
        [
            r"\begin{PURHDramaticText}",
            fragment,
            r"\end{PURHDramaticText}",
        ]
    )
